import { Word } from '../types';

export type RawHskEntry = [string, string, string];

export function buildHskWords(entries: RawHskEntry[]): Word[] {
  return entries.map(([char, pinyin, rawMeaning]) => {
    const cleanChar = char.replace(/[（(].*?[）)]/g, '').trim();
    const meaning = rawMeaning.trim();
    const lower = meaning.toLowerCase();

    let grammar = 'Noun / Verb.';
    let sentence = '';
    let translation = '';

    if (char.includes('叹词') || ['嗨', '呵', '嘿', '哼', '啦', '嘛', '哦', '哇', '喂'].includes(cleanChar)) {
      grammar = 'Interjection / Particle.';
      sentence = `“${cleanChar}，请注意听我解释这件事。”`;
      translation = `"${meaning || 'Hey'}, please listen carefully to my explanation."`;
    } else if (
      lower.includes('measure word') ||
      lower.includes('meaure word') ||
      ['磅', '串', '丛', '栋', '番', '罐', '粒', '枚', '艘', '窝', '株', '幢'].includes(cleanChar)
    ) {
      grammar = 'Measure word.';
      sentence = `这里陈列着几${cleanChar}珍贵的样品。`;
      translation = `Several precious samples (${meaning}) are displayed here.`;
    } else if (cleanChar.length === 4) {
      grammar = 'Idiom (成语) / Set Phrase.';
      sentence = `在实际工作中，我们应当懂得“${cleanChar}”的道理。`;
      translation = `In practical work, we should understand the principle of "${meaning.toLowerCase()}".`;
    } else if (
      lower.startsWith('to ') ||
      lower.startsWith('be ') ||
      lower.includes('make ') ||
      lower.includes('take ') ||
      lower.includes('give ') ||
      lower.includes('hold ') ||
      lower.includes('look ')
    ) {
      grammar = 'Verb.';
      sentence = `我们必须认真${cleanChar}这个问题，妥善解决困难。`;
      translation = `We must seriously address (${meaning.toLowerCase()}) this matter and resolve the difficulties properly.`;
    } else if (
      lower.endsWith('ly') ||
      ['巴不得', '并非', '不妨', '不禁', '不免', '不时', '不由得', '不止', '顿时', '额外', '而已', '反之', '凡是', '公然', '固然', '过于', '姑且', '恨不得', '胡乱', '即便', '即将', '及早', '接连', '进而', '近来', '据悉', '况且', '历来', '连年', '屡次', '免得', '明明', '默默', '宁肯', '宁愿', '偏偏', '颇', '起初', '起码', '恰巧', '尚且', '时常', '时而', '随即', '索性', '倘若', '特意', '统统', '万分', '唯独', '未免', '无比', '无非', '务必', '先前', '向来', '一旦', '一度', '一贯', '一向', '以便', '以免', '以至', '以致', '亦', '依然', '隐约', '犹如', '愈', '预先', '暂且', '照样', '终究', '逐年', '专程', '足以'].includes(cleanChar)
    ) {
      grammar = 'Adverb / Conjunction.';
      sentence = `在这种情况下，大家${cleanChar}能够保持冷静与理智。`;
      translation = `Under such circumstances, everyone can still remain calm (${meaning.toLowerCase()}).`;
    } else if (
      lower.includes('ous') ||
      lower.includes('ful') ||
      lower.includes('ive') ||
      lower.includes('able') ||
      lower.includes('ic') ||
      lower.includes('al')
    ) {
      grammar = 'Adjective.';
      sentence = `这种${cleanChar}的表现给所有人留下了深刻的印象。`;
      translation = `This ${meaning.toLowerCase()} expression left a deep impression on everyone.`;
    } else {
      grammar = 'Noun / Verb.';
      sentence = `这篇文章深入探讨了关于“${cleanChar}”的重要内容。`;
      translation = `This article explores important aspects regarding "${meaning.toLowerCase()}".`;
    }

    return {
      char,
      pinyin,
      meaning,
      grammar,
      examples: [
        {
          sentence,
          translation,
        },
      ],
    };
  });
}

